// 最新系の質問かどうかを判定し、カテゴリを返す。該当しなければ null。
// 「仕組み」を聞く質問（例：選挙の仕組みは？）は安定知識なので対象外にする。
export function detectLatestTopic(text) {
  const t = String(text ?? "").replace(/[\s　]/g, "");
  if (!t) return null;
  if (/仕組み|とは|って何|なぜ|どうして|理由|意味/.test(t) && !/今|今日|最近|最新/.test(t)) return null;
  for (const [cat, keys] of LATEST_KEYS) {
    for (const k of keys) {
      if (t.includes(k.replace(/[\s　]/g, ""))) return cat;
    }
  }
  if (/(今|今日|最近|最新|現在).{0,8}(どうなっ|情勢|状況|ニュース)/.test(t)) return "general";
  return null;
}

// カテゴリのプールから1文を選ぶ。used（直近で使った文の配列）に含まれる文は避ける。
export function pickHonestyLine(category, used = []) {
  const pool = HONESTY_POOL[category] || HONESTY_POOL.other;
  const fresh = pool.filter((l) => !used.includes(l));
  const src = fresh.length ? fresh : pool;
  return src[Math.floor(Math.random() * src.length)];
}

export function countHonesty() {
  return Object.values(HONESTY_POOL).reduce((a, p) => a + p.length, 0);
}
